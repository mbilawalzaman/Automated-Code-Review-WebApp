"""Exclude generated/vendor paths from style and language-tool findings (REV-002)."""

from __future__ import annotations

import os
import re
from typing import Iterable, List

from models.finding import NormalizedFinding

EXCLUDED_DIR_PARTS = {
    "vendor",
    "node_modules",
    "dist",
    "build",
    "coverage",
    ".git",
    ".venv",
    "venv",
    "__pycache__",
    "public/build",
    "storage/framework",
    "bootstrap/cache",
}

EXCLUDED_FILE_SUFFIXES = (
    ".min.js",
    ".min.css",
    ".map",
    ".lock",
)

GENERATED_NAME_RE = re.compile(
    r"(^|/)(generated|autogenerated|auto-generated)(/|$)",
    re.IGNORECASE,
)


def is_excluded_path(path: str | None) -> bool:
    if not path:
        return False

    normalized = path.replace("\\", "/").lstrip("./")
    lower = normalized.lower()

    if any(lower.endswith(suffix) for suffix in EXCLUDED_FILE_SUFFIXES):
        return True

    if GENERATED_NAME_RE.search(lower):
        return True

    parts = lower.split("/")
    if any(part in EXCLUDED_DIR_PARTS for part in parts):
        return True

    # Also catch nested public/build style paths expressed as joined segments.
    joined = "/".join(parts)
    return any(token in joined for token in ("/vendor/", "/node_modules/", "/dist/", "/build/"))


def filter_findings(findings: Iterable[NormalizedFinding]) -> List[NormalizedFinding]:
    """Drop style/quality findings that only point at vendor/generated paths."""
    kept: List[NormalizedFinding] = []
    for finding in findings:
        # Secrets scanners should still report vendor leaks; language style tools are filtered.
        if finding.tool_name in {"gitleaks", "osv-scanner", "objective-compliance"}:
            kept.append(finding)
            continue
        if is_excluded_path(finding.file_path):
            continue
        kept.append(finding)
    return kept


def scanner_exclude_args(tool: str) -> List[str]:
    """Optional CLI ignore args for tools that support them."""
    if tool == "eslint":
        return ["--ignore-pattern", "vendor/**", "--ignore-pattern", "node_modules/**", "--ignore-pattern", "dist/**"]
    if tool == "ruff":
        return ["--exclude", "vendor,node_modules,dist,build,.venv"]
    if tool == "bandit":
        return ["-x", "vendor,node_modules,dist,build,.venv"]
    return []
